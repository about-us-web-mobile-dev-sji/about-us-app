import { UUID } from 'crypto';
import { SchoolStatus } from '../enums/school-status.enum.js';

export interface SchoolProps {
  id?: UUID;
  name: string;
  address: string | null;
  city: string | null;
  postalCode: string | null;
  country: string | null;
  phoneNumber: string | null;
  email: string | null;
  website: string | null;
  status: SchoolStatus;
  adminUserId: string | null;
  createdAt: Date;
  updatedAt: Date;
  createdBy: string;
}

export type NewSchool = Omit<SchoolProps, 'id'>;

export class School {
  private constructor(private props: SchoolProps) {}

  static create(input: {
    name: string;
    address?: string | null;
    city?: string | null;
    postalCode?: string | null;
    country?: string | null;
    phoneNumber?: string | null;
    email?: string | null;
    website?: string | null;
    adminUserId?: string | null;
    createdBy: string;
  }): School {
    const now = new Date();

    if (!Number.isFinite(now.getTime())) {
      throw new Error('Invalid date');
    }

    if (!input.name?.trim()) {
      throw new Error('School name is required');
    }

    if (!input.createdBy?.trim()) {
      throw new Error('createdBy is required');
    }

    const props: SchoolProps = {
      id: undefined, // Will be generated by the database
      name: input.name.trim(),
      address: input.address?.trim() || null,
      city: input.city?.trim() || null,
      postalCode: input.postalCode?.trim() || null,
      country: input.country?.trim() || null,
      phoneNumber: input.phoneNumber?.trim() || null,
      email: input.email?.trim() || null,
      website: input.website?.trim() || null,
      status: SchoolStatus.ACTIVE,
      adminUserId: input.adminUserId || null,
      createdAt: new Date(now),
      updatedAt: new Date(now),
      createdBy: input.createdBy.trim(),
    };

    return new School(props);
  }

  static reconstitute(props: SchoolProps): School {
    return new School(structuredClone(props));
  }

  get id(): UUID | undefined {
    return this.props.id;
  }

  get name(): string {
    return this.props.name;
  }

  get status(): SchoolStatus {
    return this.props.status;
  }

  updateStatus(newStatus: SchoolStatus): void {
    if (!Object.values(SchoolStatus).includes(newStatus)) {
      throw new Error('Invalid school status');
    }
    this.props.status = newStatus;
    this.props.updatedAt = new Date();
  }

  assignAdmin(adminUserId: string): void {
    if (!adminUserId?.trim()) {
      throw new Error('Admin user ID is required');
    }
    this.props.adminUserId = adminUserId.trim();
    this.props.updatedAt = new Date();
  }

  removeAdmin(): void {
    this.props.adminUserId = null;
    this.props.updatedAt = new Date();
  }

  toPrimitives(): SchoolProps {
    return structuredClone(this.props);
  }
}
